<?php

declare(strict_types=1);

$input = $argv[1] ?? 'build/coverage.xml';
$output = $argv[2] ?? 'build/coverage-report.md';

if (! is_file($input)) {
    fwrite(STDERR, "Coverage file {$input} not found.\n");
    exit(1);
}

$coverage = simplexml_load_file($input);
if ($coverage === false || ! isset($coverage->project->metrics)) {
    fwrite(STDERR, "Coverage file {$input} is not a valid Clover report.\n");
    exit(1);
}

$projectRoot = getcwd();
$rows = [];
$files = $coverage->xpath('/coverage/project//file');

foreach ($files === false ? [] : $files as $file) {
    $path = (string) $file['name'];
    $relativePath = str_starts_with($path, $projectRoot . DIRECTORY_SEPARATOR)
        ? substr($path, strlen($projectRoot) + 1)
        : $path;
    $uncoveredLines = [];

    foreach ($file->line as $line) {
        if ((string) $line['type'] === 'stmt' && (int) $line['count'] === 0) {
            $uncoveredLines[] = (int) $line['num'];
        }
    }

    if ($uncoveredLines === []) {
        continue;
    }

    sort($uncoveredLines);
    $rows[] = [
        'path' => $relativePath,
        'lines' => $uncoveredLines,
        'reason' => match (true) {
            $relativePath === 'app/Http/Controllers/McpHttpController.php'
                => 'The SSE response callback is not drained by the unit test because it emits a 30-second keep-alive stream; request parsing and response headers are covered.',
            str_contains($relativePath, '/Services/Normalize/')
                => 'Alternate source metadata shapes and invalid optional values are not all represented by the fixture set.',
            str_contains($relativePath, '/Services/Search/')
                => 'Remaining search filter and pagination combinations need dedicated request fixtures.',
            str_contains($relativePath, '/Repositories/'), str_contains($relativePath, '/Persist/')
                => 'Persistence branches depend on database state and need database-backed integration fixtures.',
            str_contains($relativePath, '/Support/Code/')
                => 'Remaining canonicalization and qualification edge inputs are not represented by the current cases.',
            str_contains($relativePath, '/Data/')
                => 'Remaining constructor invariants and optional-field combinations are not represented by current draft fixtures.',
            str_contains($relativePath, '/Http/Requests/')
                => 'Additional validation input combinations are not represented by current request fixtures.',
            str_contains($relativePath, '/Http/'), str_contains($relativePath, '/Resources/')
                => 'Endpoint and serialization branches need focused request or payload fixtures.',
            str_contains($relativePath, '/Services/Crawl/')
                => 'Remaining queue and crawl lifecycle conditions need focused state-transition fixtures.',
            str_contains($relativePath, '/Services/Mcp/')
                => 'Remaining protocol dispatch and authorization input variants need focused message fixtures.',
            str_contains($relativePath, '/Observability/'), str_contains($relativePath, '/Notifications/')
                => 'Telemetry and delivery branches need focused fake-client or failure-path fixtures.',
            str_contains($relativePath, '/Jobs/'), str_contains($relativePath, '/Console/'), str_contains($relativePath, '/Commands/')
                => 'Lifecycle and orchestration branches need focused queue or command fixtures.',
            default
            => 'The current unit and feature inputs do not reach these statements; add a focused fixture when the behavior is in scope.',
        },
    ];
}

usort($rows, static fn(array $left, array $right): int => $left['path'] <=> $right['path']);

$metrics = $coverage->project->metrics;
$statements = (int) $metrics['statements'];
$covered = (int) $metrics['coveredstatements'];
$percentage = $statements > 0 ? ($covered / $statements) * 100 : 0;
$report = [
    '# Coverage Gaps',
    '',
    sprintf('Combined unit and feature statement coverage: **%.2f%% (%d/%d)**.', $percentage, $covered, $statements),
    '',
    'Source: `build/coverage.xml`, generated by `composer test:coverage` in the CI image.',
    '',
    'Uncovered statement lines below are not exercised by the current suite. The reason column identifies the next test boundary suggested by each component; it does not claim those statements are defective.',
    '',
    '| File | Uncovered statement lines | Why they remain uncovered |',
    '| --- | --- | --- |',
];

foreach ($rows as $row) {
    $path = str_replace('|', '\\|', $row['path']);
    $lines = implode(', ', $row['lines']);
    $report[] = sprintf('| `%s` | %s | %s |', $path, $lines, $row['reason']);
}

if ($rows === []) {
    $report[] = '| None | — | Every reported application statement is covered. |';
}

$directory = dirname($output);
if (! is_dir($directory) && ! mkdir($directory, 0777, true) && ! is_dir($directory)) {
    fwrite(STDERR, "Unable to create report directory {$directory}.\n");
    exit(1);
}

if (file_put_contents($output, implode("\n", $report) . "\n") === false) {
    fwrite(STDERR, "Unable to write coverage report {$output}.\n");
    exit(1);
}

printf("Wrote %d uncovered-file entries to %s.\n", count($rows), $output);
